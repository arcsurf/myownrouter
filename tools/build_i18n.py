#!/usr/bin/env python3
"""Build the web UI dictionaries from i18n/translations.tsv.

Spanish is the source language: the UI calls t("texto en español", ...args).
This script writes files/www/mor/i18n/<lang>.js and checks that every t('...')
key used in the code has a translation and that {N} placeholders match.
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TSV = ROOT / 'i18n' / 'translations.tsv'
OUT = ROOT / 'files' / 'www' / 'mor' / 'i18n'
SOURCES = [ROOT / 'files/www/mor' / f for f in ('core.js', 'pages-main.js', 'pages-more.js')]
BACKEND = ROOT / 'files/usr/share/rpcd/ucode/myownrouter'
LANGS = ['en', 'fr', 'de']

def load():
    rows = {}
    for n, line in enumerate(TSV.read_text(encoding='utf-8').split('\n'), 1):
        if not line or line.startswith('#'):
            continue
        cols = line.split('\t')
        if len(cols) != 1 + len(LANGS):
            sys.exit(f'{TSV.name}:{n}: expected {1 + len(LANGS)} columns, got {len(cols)}')
        if cols[0] in rows:
            sys.exit(f'{TSV.name}:{n}: duplicate key {cols[0]!r}')
        rows[cols[0]] = cols[1:]
    return rows

def used_keys():
    keys = set()
    lit = r"'((?:[^'\\\n]|\\.)*)'"
    for f in SOURCES:
        for m in re.finditer(r"\bt\(" + lit, f.read_text(encoding='utf-8')):
            keys.add(m.group(1).replace("\\'", "'").replace('\\\\', '\\'))
    for m in re.finditer(r"fail\(" + lit, BACKEND.read_text(encoding='utf-8')):
        keys.add(m.group(1))
    return keys

def main():
    rows = load()
    errors = []
    for k in sorted(used_keys()):
        if k not in rows:
            errors.append(f'missing translation: {k!r}')
    ph = re.compile(r'\{\d+\}')
    for k, tr in rows.items():
        for lang, v in zip(LANGS, tr):
            if sorted(ph.findall(k)) != sorted(ph.findall(v)):
                errors.append(f'{lang}: placeholder mismatch in {k!r}')
    if errors:
        print('\n'.join(errors))
        sys.exit(1)
    OUT.mkdir(parents=True, exist_ok=True)
    for i, lang in enumerate(LANGS):
        d = {k: tr[i] for k, tr in rows.items() if tr[i] != k}
        body = json.dumps(d, ensure_ascii=False, indent='\t', sort_keys=True)
        (OUT / f'{lang}.js').write_text(
            f'/* Generated by tools/build_i18n.py from i18n/translations.tsv — do not edit. */\n'
            f'MOR_I18N.{lang} = {body};\n', encoding='utf-8')
        print(f'{lang}: {len(d)} strings')
    unused = set(rows) - used_keys() - {'La imagen no es válida para este equipo', 'auto', 'Imagen inválida'}
    if unused:
        print('unused keys:', ', '.join(sorted(unused)))

if __name__ == '__main__':
    main()
